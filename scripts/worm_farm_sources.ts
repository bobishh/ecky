import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Compose downloadable, self-contained sources. No run-time include or hidden library.
export function sourceForms(source: string): string[] {
  const result: string[] = [];
  let depth = 0;
  let start = 0;
  let quoted = false;
  let comment = false;
  for (let i = 0; i < source.length; i++) {
    const c = source[i];
    if (comment) { if (c === '\n') comment = false; continue; }
    if (quoted) { if (c === '\\') i++; else if (c === '"') quoted = false; continue; }
    if (c === ';') { comment = true; continue; }
    if (c === '"') { quoted = true; continue; }
    if (c === '(') { if (depth++ === 0) start = i; }
    if (c === ')') { if (--depth < 0) throw new Error('Unbalanced source'); if (depth === 0) result.push(source.slice(start, i + 1)); }
  }
  if (depth || quoted) throw new Error('Unterminated source');
  return result;
}

const base = 'docs/books/ecky-ir/examples/worm-farm';
const read = (root: string, file: string) => fs.readFileSync(path.join(root, base, file), 'utf8');
const definitions = (source: string) => sourceForms(source).filter(form => form.startsWith('(define-component ')).join('\n\n');

function placed(source: string, prefix: string, xyz: string): string {
  const part = source.match(/^\(part\s+([^\s()]+)\s+/);
  if (part) {
    const body = source.slice(part[0].length, -1);
    return `(part ${prefix}-${part[1]}\n      (translate ${xyz}\n${body}))`;
  }
  if (source.startsWith('(let* ')) {
    const children = sourceForms(source.slice(1, -1));
    let result = source;
    for (const child of children.slice(1)) result = result.replace(child, placed(child, prefix, xyz));
    return result;
  }
  throw new Error(`Unsupported farm part group: ${source.slice(0, 40)}`);
}

export function buildWormFarmSources(root: string): Map<string, string> {
  const tractor = read(root, '04-tractor.ecky');
  const worm = read(root, '01-worm.ecky');
  const outputs = new Map<string, string>();
  const header = '; Generated by scripts/worm_farm_sources.ts from the chapter models.\n';
  outputs.set('tractor-assembled.ecky', header + tractor.replace('(toggle print_layout true', '(toggle print_layout false'));
  outputs.set('tractor-fit-coupon.ecky', `${header}${definitions(tractor)}

(model
  (meta :title "Axle, wheel and snap-rivet fit coupon")
  (params
    (number wheel_clearance 0.4mm :label "Wheel running clearance" :min 0.2 :max 0.6 :step 0.05)
    (number snap_interference 0.25mm :label "Rivet snap interference" :min 0.1 :max 0.35 :step 0.05))
  (part axle (tractor-axle :axle-length 16mm))
  (part wheel (translate 18mm 0 0 (tractor-wheel :running-clearance wheel_clearance)))
  (part rivet (translate -12mm 0 0 (tractor-rivet :snap-interference snap_interference)))
  (verify (tag three-separate-pieces) (metric pieces (stl connected-component-count)) (expect pieces (= 3))))
`);
  outputs.set('worm-joint-coupon.ecky', `${header}${definitions(worm)}

(model
  (meta :title "Two captive worm links")
  (params
    (number joint-clearance 0.6mm :label "Joint clearance" :min 0.4 :max 0.8 :step 0.05))
  (part ball-link (worm-link :joint-clearance joint-clearance :has-socket false))
  (part socket-link (translate 23mm 0 0 (worm-link :joint-clearance joint-clearance :has-ball false)))
  (verify (tag two-moving-links) (metric pieces (stl connected-component-count)) (expect pieces (= 2))))
`);
  const models = [
    ['01-worm.ecky', 'worm', '-100mm -35mm 0mm'],
    ['02-mushroom-house.ecky', 'mushroom', '-65mm 40mm 0mm'],
    ['03-rake.ecky', 'tool', '-20mm 75mm 0mm'],
    ['04-tractor.ecky', 'tractor', '40mm 35mm 0mm'],
    ['05-garden.ecky', 'garden', '-15mm 100mm 0mm'],
  ];
  const helpers: string[] = [], params: string[] = [], parts: string[] = [];
  for (const [file, prefix, xyz] of models) {
    const source = read(root, file);
    const forms = sourceForms(source);
    helpers.push(...forms.filter(form => form.startsWith('(define-component ')));
    const model = forms.find(form => form.startsWith('(model'))!;
    const children = sourceForms(model.slice(1, -1));
    for (const child of children) {
      if (child.startsWith('(params')) params.push(...sourceForms(child.slice(1, -1)));
      if (child.startsWith('(part ') || child.startsWith('(let* ')) parts.push(placed(child, prefix, xyz));
    }
  }
  const assembledParams = params.map(form => form.replace(/(toggle (?:print_layout|house_print_layout)) true/, '$1 false'));
  outputs.set('06-farm.ecky', `${header}${helpers.join('\n\n')}

(model
  (meta :title "Worm Farm")
  (params\n${assembledParams.map(form => '    ' + form).join('\n')})
${parts.map(form => '  ' + form).join('\n\n')}
  (view peek_inside (offset-part mushroom-roof 0 0 24mm))
  (verify (tag closed-farm) (metric bad-edges (stl non-manifold-edge-count)) (expect bad-edges (= 0)))
  (verify (tag separate-mechanisms) (metric pieces (stl connected-component-count)) (expect pieces (= 25))))
`);
  return outputs;
}

export function syncWormFarmSources(root: string, check = false): void {
  for (const [name, content] of buildWormFarmSources(root)) {
    const file = path.join(root, base, name);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) throw new Error(`Stale composed model: ${name}`);
    } else fs.writeFileSync(file, content);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  syncWormFarmSources(process.cwd(), process.argv.includes('--check'));
}
